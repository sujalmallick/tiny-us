def kotlin():
    out = ['package com.example.ui.theme', '',
           'import androidx.compose.ui.graphics.Color',
           'import androidx.compose.ui.graphics.SolidColor',
           'import androidx.compose.ui.graphics.vector.ImageVector',
           'import androidx.compose.ui.graphics.vector.path',
           'import androidx.compose.ui.unit.dp', '',
           '// Generated by tools/pixelfont/build_pixel_icons.py; edit the grids there, not here.', '',
           '/**',
           ' * The Tiny Us pixel icon set (Plan 03, Phase 5): 12x12 pixel grids, so at the usual 24 dp',
           ' * size one icon pixel is 2 dp. Same names as the Material icons they replace; tinting works',
           ' * as usual.',
           ' */',
           'object PixelIcons {']
    for name in sorted(ICONS):
        rows = ", ".join(f'"{r}"' for r in ICONS[name])
        out.append(f'    val {name}: ImageVector by lazy {{ pixelIcon("{name}", {rows}) }}')
    out += ['}', '',
            'private fun pixelIcon(name: String, vararg rows: String): ImageVector =',
            '    ImageVector.Builder(',
            '        name = "Pixel.$name", defaultWidth = 24.dp, defaultHeight = 24.dp,',
            '        viewportWidth = 12f, viewportHeight = 12f',
            '    ).apply {',
            '        path(fill = SolidColor(Color.Black)) {',
            '            for ((y, row) in rows.withIndex()) {',
            '                var x = 0',
            '                while (x < row.length) {',
            "                    if (row[x] != '#') { x++; continue }",
            '                    var end = x',
            "                    while (end + 1 < row.length && row[end + 1] == '#') end++",
            '                    moveTo(x.toFloat(), y.toFloat())',
            '                    lineTo(end + 1f, y.toFloat())',
            '                    lineTo(end + 1f, y + 1f)',
            '                    lineTo(x.toFloat(), y + 1f)',
            '                    close()',
            '                    x = end + 1',
            '                }',
            '            }',
            '        }',
            '    }.build()', '']
    return "\n".join(out)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.normpath(os.path.join(here, "..", "..", "app", "src", "main", "java", "com", "example", "ui", "theme", "PixelIcons.kt"))
    open(path, "w", encoding="utf-8", newline="\n").write(kotlin())
    print("wrote", path, len(ICONS), "icons")

def icon(name, *rows):
    rows = list(rows)
    assert len(rows) == 12, (name, len(rows))
    for r in rows:
        assert len(r) == 12, (name, r, len(r))
        assert set(r) <= {".", "#"}, (name, r)
    ICONS[name] = rows


def mirror(name, source):
    ICONS[name] = [r[::-1] for r in ICONS[source]]


def same(name, source):
    ICONS[name] = ICONS[source]


